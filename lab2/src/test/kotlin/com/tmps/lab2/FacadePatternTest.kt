package com.tmps.lab2

import com.tmps.lab2.patterns.adapter.CurrencyConverter
import com.tmps.lab2.patterns.decorator.PaymentProcessor
import com.tmps.lab2.patterns.decorator.PaymentResult
import com.tmps.lab2.patterns.facade.CheckoutItemRequest
import com.tmps.lab2.patterns.facade.CheckoutRequest
import com.tmps.lab2.patterns.facade.CheckoutResponse
import com.tmps.lab2.patterns.facade.StoreCheckoutFacade

class FacadePatternTest {

    private class StubPaymentProcessor(
        private val shouldSucceed: Boolean = true
    ) : PaymentProcessor {
        var lastOrderId: Long? = null
        var lastAmount: Double? = null
        var lastCurrency: String? = null

        override fun processPayment(orderId: Long, customerName: String, amount: Double, currency: String): PaymentResult {
            lastOrderId = orderId
            lastAmount = amount
            lastCurrency = currency
            return if (shouldSucceed) {
                PaymentResult.Success(
                    transactionId = "STUB-TX-$orderId",
                    amount = amount,
                    currency = currency
                )
            } else {
                PaymentResult.Failure(
                    errorCode = "SIMULATED_REJECTION",
                    reason = "Payment rejected by security/banking gateway"
                )
            }
        }
    }

    private class StubCurrencyConverter(
        private val fixedRate: Double = 0.05
    ) : CurrencyConverter {
        override fun getExchangeRate(fromCurrency: String, toCurrency: String): Double {
            return if (fromCurrency == toCurrency) 1.0 else fixedRate
        }

        override fun convert(amount: Double, fromCurrency: String, toCurrency: String): Double {
            return if (fromCurrency == toCurrency) amount else amount * fixedRate
        }
    }

    fun testFacadeCoordinatesFullRetailCheckoutPipelineSuccessfully() {
        val stubProcessor = StubPaymentProcessor(shouldSucceed = true)
        val facade = StoreCheckoutFacade(
            paymentProcessor = stubProcessor,
            currencyConverter = StubCurrencyConverter()
        )

        val request = CheckoutRequest(
            customerName = "Petru Rares",
            items = listOf(
                CheckoutItemRequest("Optical Mouse", quantity = 2, unitPrice = 150.0), // 300
                CheckoutItemRequest("Keyboard Pad", quantity = 1, unitPrice = 100.0)    // 100
            ),
            isWholesale = false,
            shippingAddress = "Chisinau",
            isPriority = true,
            targetCurrency = "MDL"
        )

        val response = facade.checkout(request)

        check(response is CheckoutResponse.Success) { "Expected CheckoutResponse.Success, got $response" }
        // Subtotal = 400.0, VAT 20% = 80.0, Total = 480.0
        val expectedTotal = 400.0 * 1.20
        check(kotlin.math.abs(response.chargedAmount - expectedTotal) < 0.001) {
            "Expected total $expectedTotal, got ${response.chargedAmount}"
        }
        check(stubProcessor.lastAmount != null && kotlin.math.abs(stubProcessor.lastAmount!! - expectedTotal) < 0.001) {
            "Payment processor must receive the VAT-inclusive total"
        }
        check(stubProcessor.lastCurrency == "MDL") { "Payment currency should be MDL" }
        check(response.order.customerName == "Petru Rares") { "Customer name must match request" }
        check(response.receipt.contains("RETAIL RECEIPT")) { "Receipt must be generated by retail printer" }
    }

    fun testFacadeConvertsCurrencyViaAdapterForForeignOrders() {
        val stubProcessor = StubPaymentProcessor(shouldSucceed = true)
        val fixedEurRate = 0.051 // 1 MDL = 0.051 EUR
        val facade = StoreCheckoutFacade(
            paymentProcessor = stubProcessor,
            currencyConverter = StubCurrencyConverter(fixedRate = fixedEurRate)
        )

        val request = CheckoutRequest(
            customerName = "Foreign Buyer",
            items = listOf(
                CheckoutItemRequest("External SSD", quantity = 1, unitPrice = 1000.0)
            ),
            targetCurrency = "EUR"
        )

        val response = facade.checkout(request)

        check(response is CheckoutResponse.Success) { "Expected CheckoutResponse.Success, got $response" }
        // Base total: 1000 * 1.20 = 1200 MDL. In EUR: 1200 * 0.051 = 61.20 EUR
        val expectedBase = 1200.0
        val expectedEur = 1200.0 * fixedEurRate

        check(kotlin.math.abs(response.originalTotal - expectedBase) < 0.001) { "Original base total should be $expectedBase" }
        check(kotlin.math.abs(response.chargedAmount - expectedEur) < 0.001) { "Charged amount should be $expectedEur EUR" }
        check(response.chargedCurrency == "EUR") { "Charged currency should be EUR" }
        check(stubProcessor.lastCurrency == "EUR") { "Payment processor must receive EUR" }
    }

    fun testFacadeHandlesDownstreamPaymentRejectionGracefullyWithoutPrintingReceipt() {
        val failingProcessor = StubPaymentProcessor(shouldSucceed = false)
        val facade = StoreCheckoutFacade(
            paymentProcessor = failingProcessor,
            currencyConverter = StubCurrencyConverter()
        )

        val request = CheckoutRequest(
            customerName = "Declined Customer",
            items = listOf(
                CheckoutItemRequest("Flash Drive", quantity = 1, unitPrice = 50.0)
            )
        )

        val response = facade.checkout(request)

        check(response is CheckoutResponse.Failed) { "Expected CheckoutResponse.Failed, got $response" }
        check(response.paymentResult.errorCode == "SIMULATED_REJECTION") {
            "Expected SIMULATED_REJECTION error code, got ${response.paymentResult.errorCode}"
        }
        check(response.order != null) { "Failed response should retain created order metadata for recovery" }
    }
}
